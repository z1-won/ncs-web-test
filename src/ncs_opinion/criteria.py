"""내용 검수 기준 붙이기 — 의견 글에 걸리는 지침 조항을 골라 사람이 판단할 때 볼 기준으로 적어 준다. 판정을 바꾸지 않는다. I/O 없음.

요구사항정의서(REQ-02-003)의 내용 검수 기준 두 가지(V0.17·V0.23 변경근거):
  F04 「NCS-학습모듈 준용 집필 기준 및 변경 허용 범위 안내」('26.8.7) 2장 — 변경 집필 유형 넷의 허용 범위
      2-1 용어/단어 변경   수행준거를 준용하는 범위에서 적절한 용어로 변경 가능(내용 전문가 판단 필수). 단순 윤문 차원의 변경은 불가
      2-2 법령/지침 변경   수행준거를 준용하는 범위에서 신규 법령·지침으로 변경 가능(내용 전문가 판단 필수)
      2-3 통합/분리        NCS에 능력단위요소로 없는 주제를 학습으로 추가 불가, 능력단위요소를 나눠 타 능력단위의 요소와 통합 불가
      2-4 띄어쓰기         학습명·학습 내용은 능력단위요소명, 학습목표는 수행준거를 준용(학습목표 문장 안의 띄어쓰기는 수정 가능).
                           국어 규범과 다르면 NCS 표기를 따르되 명백한 표기 오류는 수정 가능
  F07 「원고 집필 및 지식재산권 양도 계약서」 제3조 2항 — 표절의 범위 ①~⑥
낱말로 고른다(용어·법령·통합·분리·띄어쓰기·출처·인용…). 낱말이 없으면 붙이지 않고, 유형이 '용어 변경'이면 2-1을 붙인다.
허용 범위 안인지, 표절인지는 정하지 않는다 — 그 판단은 내용 전문가와 직능연의 것이다.
"""

from __future__ import annotations

import re

from ncs_core.law_catalog import law_names_in

TERM = re.compile(r"용어|단어|명칭|표현을|표기를|로\s*통일|으로\s*통일")
LAW = re.compile(r"법령|법률|시행령|시행규칙|고시|훈령|지침|개정|폐지|현행")
MERGE = re.compile(r"통합|분리|합쳐|합치|나누어|나눠|세분")
SPACING = re.compile(r"띄어\s*쓰기|붙여\s*쓰기")
SOURCE = re.compile(r"출처|인용|표절|저작권|재인용|무단")
F04 = "변경 허용 범위(F04 {no}): {text}"
SCOPE = {
    "2-1": "용어·단어는 수행준거를 준용하는 범위에서만 적절한 것으로 바꿀 수 있고 내용 전문가(집필진) 판단이 필요합니다. 단순 윤문 차원의 변경은 불가입니다.",
    "2-2": "법령·지침이 바뀌어 기존 내용이 맞지 않으면 수행준거를 준용하는 범위에서 신규 법령·지침으로 바꿀 수 있고 내용 전문가 판단이 필요합니다.",
    "2-3": "NCS에 능력단위요소로 없는 주제를 학습으로 새로 넣을 수 없고, 능력단위요소를 나눠 타 능력단위의 요소와 통합할 수 없습니다. 요소 간 통합과 한 요소의 분리는 가능합니다.",
    "2-4": "학습명·학습 내용은 능력단위요소명의 띄어쓰기를, 학습목표는 수행준거를 준용합니다(학습목표 문장 안의 띄어쓰기는 수정 가능). 국어 규범과 달라도 NCS 표기를 따르고, 명백한 표기 오류만 고칩니다.",
}
PLAGIARISM = (     # (번호, 고르는 낱말, 조항 요지) — F07 제3조 2항
    ("②", re.compile(r"번역"), "타인의 저작물을 번역해 쓰면서 출처를 표기하지 않음"),
    ("③", re.compile(r"재인용|원문을\s*(?:직접\s*)?본|1차\s*문헌"), "재인용 표시를 해야 하는데 원문을 직접 본 것처럼 1차 문헌의 출처를 표시함"),
    ("④", re.compile(r"분량|과다|지나치|대부분|주종"), "출처를 표시했어도 인용의 양·질이 정당한 범위를 넘어 주종 관계가 됨"),
    ("⑤", re.compile(r"일부(?:에)?만|일부\s*만"), "타인의 저작물을 쓰고 일부에만 출처를 표시함"),
    ("⑥", re.compile(r"그대로|동일(?:하게|한)|복사|베낀|옮긴|옮겨"), "상당 부분을 참조했다고 표시했지만 실은 그대로 가져다 씀"),
)
FIRST = ("①", "타인의 독창적인 아이디어나 저작물을 쓰면서 출처를 표기하지 않음")


def criteria_notes(text: str, kind: str = "") -> list[str]:
    """의견 글(과 LLM이 준 유형) → 붙일 검수 기준 문장 목록(없으면 빈 목록)."""
    text = text or ""
    notes = []
    if kind == "용어 변경" or TERM.search(text):
        notes.append(F04.format(no="2-1", text=SCOPE["2-1"]))
    if LAW.search(text) or law_names_in(text, None):
        notes.append(F04.format(no="2-2", text=SCOPE["2-2"]))
    if MERGE.search(text):
        notes.append(F04.format(no="2-3", text=SCOPE["2-3"]))
    if SPACING.search(text):
        notes.append(F04.format(no="2-4", text=SCOPE["2-4"]))
    if SOURCE.search(text):
        found = [(no, gist) for no, pattern, gist in PLAGIARISM if pattern.search(text)] or [FIRST]
        notes.append("표절 범위(F07 제3조 2항 " + "·".join(no for no, _ in found) + "): " + " / ".join(gist for _, gist in found)
                     + " — 이 범위에 해당하지 않아야 합니다.")
    return notes
