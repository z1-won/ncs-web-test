"""원고 문장 추천(REQ-02-004)의 설정값과 그 근거 — 문장 종류별 규정 꼴, 후보 수, AI 후보 검증 문턱, LLM에 보내는 양.

근거
- 문장 종류와 규정 꼴: F02 검수 확인서 항목과 「PoC② 검수 자료 안내서」 A-04(문장·제목 종결), 판정 원칙의 결정(2026-11-15).
  학습 목표 '~할 수 있다.'(개요 ①, 주어 삭제) · 수행 순서 '~한다.'('~할 수 있다.'도 적합, 수행 ④) ·
  교수 방법·학습 방법 '~한다.'(교수·학습 ②④, '~할 수 있다.'는 부적합) · 평가 항목 '~여부/~능력/~수준/~정도' 명사형, 마침표 없음(평가 ④) ·
  학습명·수행 내용 제목 '~하기'(차례 ①, 수행 ①) · 학습 내용명 행동명사 종결(차례 ②). 안전·유의 사항은 F02에 종결 규정이 없어
  문장 직접 입력에서만 '~한다.'를 권장 꼴로 본다(원고 전체 점검에서는 모으지 않는다).
- 판정: 고칠 문장인지와 정정 후보는 LLM이 낸다(작업 이름 sentence_suggest). 규칙 코드는 문장 모으기(extract)와
  AI 후보 검증(llm_suggest.validate — 규정 꼴 재검사, 원문에 없던 수치·영문·상호 금지, 원문 유사도 하한)만 맡는다.
  LLM 설정이 없거나 호출이 실패하면 규칙으로 대신 판정하지 않고 '판단불가'와 이유를 낸다.
- 문맥: 문장마다 자리(어느 학습·구성의 몇 번째 문장인가)와 같은 묶음의 앞·뒤 문장을 함께 보낸다(요구사항 상세 '문맥의 흐름을 고려하여').
  앞·뒤 문장은 같은 종류의 추천 대상 문장이라 새로 반출되는 글은 없다. context_chars=0이면 보내지 않는다.
- 근거 문장: 요구사항 수행예시 (1-3) '근거 있는 문장(기존 학습모듈·공공저작물) 기반 정정 후보를 순위대로'. 참고 문장 묶음(corpus.py,
  기존 학습모듈·F12 우수사례집에서 규정 꼴을 지킨 문장)에서 비슷한 문장을 LLM에 표현 참고로 보내고, 검증을 통과한 후보마다 가장 비슷한
  참고 문장을 '근거 문장'으로 붙인다. 근거 문장이 있는 후보를 앞 순위로 올린다(그 안에서는 AI가 낸 순서). 묶음이 없으면 붙이지 않고 그렇다고 알린다.
- 후보 수: 기업 기대 시연(「문장정정 후보 5순위 검토자 선택」) — 문장당 최대 5개, 순위를 붙여 검토자가 고른다.
- 역할 경계(요구사항정의서 V0.23 REQ-02-004): 종결·표현만 고친다. 전문 직무 내용을 새로 만들거나 교육 내용의 적절성을 판정하지 않는다.
- 고지: AI가 만든 문장은 집필자 서약서의 고지 대상일 수 있어 후보마다 출처('AI 생성')를 적는다.
"""

from __future__ import annotations

from dataclasses import dataclass

# 문장 종류(id = 화면 이름) → 규정 꼴. 순서가 화면 선택지 순서다.
KINDS = {
    "학습 목표": "~할 수 있다. (주어 없이)",
    "수행 순서": "~한다. (~할 수 있다.도 적합)",
    "교수 방법": "~한다.",
    "학습 방법": "~한다.",
    "안전·유의 사항": "~한다. (권장 꼴)",
    "평가 항목": "~여부 / ~능력 / ~수준 / ~정도 (마침표 없이)",
    "학습명": "~하기",
    "수행 내용 제목": "~하기",
    "학습 내용명": "행동명사로 끝남 (예: ~ 수집, ~ 분석)",
}

SOURCE_AI = "AI 생성"
NO_SUGGESTION = "추천 없음(사람이 고쳐야 함)"

# LLM이 고를 사유 유형(카드의 '상태'). 목록 밖의 답은 '기타 표현'으로 둔다.
ENDING = "종결형 위반"
REASONS = (ENDING, "주어 군더더기", "어색한 낱말", "중복 표현", "문장부호", "기타 표현")
OTHER_REASON = "기타 표현"
UNDECIDED = "판단불가"      # 문장 직접 입력에서 AI를 부르지 못함
NO_FINDING = "지적 없음"     # 문장 직접 입력에서 AI가 고칠 곳을 찾지 못함

LLM_TASK = "sentence_suggest"      # ncs_core.llm.ALLOWED_TASKS에 등록된 작업 이름 — 같은 종류의 문장 줄만 보낸다


@dataclass(frozen=True)
class SuggestConfig:
    max_candidates: int = 5         # 문장당 후보 수(순위 1~5)
    max_examples: int = 2           # 같은 원고의 참고 예문 수
    example_min: float = 0.35       # 참고 예문 글자 유사도 하한(difflib ratio)
    ai_min_similarity: float = 0.6  # AI 후보와 원문의 글자 유사도 하한 — 낮으면 내용을 바꾼 것으로 보고 버린다
    llm_max_sentences: int = 300    # 원고 한 건에서 AI에 물을 문장 수 상한
    llm_batch: int = 20             # AI 한 번에 묻는 문장 수(같은 종류끼리)
    llm_output_tokens: int = 6000   # 응답 길이 한도(지적 문장마다 후보 5개)
    context_chars: int = 120        # AI에 보내는 앞·뒤 문장의 글자 수 상한(0이면 문맥을 보내지 않음)
    max_references: int = 2         # 문장마다 AI에 보내는 참고 문장 수(참고 문장 묶음에서)
    reference_min: float = 0.35     # AI에 보내는 참고 문장의 글자 유사도 하한(같은 원고 참고 예문과 같은 값)
    ground_min: float = 0.5         # 후보의 '근거 문장'으로 인정하는 글자 유사도 하한 — 낮으면 근거 없음으로 둔다


DEFAULT_CONFIG = SuggestConfig()
