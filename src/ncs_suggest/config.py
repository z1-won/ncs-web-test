"""원고 문장 추천(REQ-02-004)의 설정값과 그 근거 — 문장 종류별 규정 꼴, 후보 수, 신뢰도 문턱, 유사 문장·LLM 조건.

근거
- 문장 종류와 규정 꼴: F02 검수 확인서 항목과 「PoC② 검수 자료 안내서」 A-04(문장·제목 종결), 판정 원칙의 결정(2026-11-15).
  학습 목표 '~할 수 있다.'(개요 ①, 주어 삭제) · 수행 순서 '~한다.'('~할 수 있다.'도 적합, 수행 ④) ·
  교수 방법·학습 방법 '~한다.'(교수·학습 ②④, '~할 수 있다.'는 부적합) · 평가 항목 '~여부/~능력/~수준/~정도' 명사형, 마침표 없음(평가 ④) ·
  학습명·수행 내용 제목 '~하기'(차례 ①, 수행 ①) · 학습 내용명 행동명사 종결(차례 ②). 안전·유의 사항은 F02에 종결 규정이 없어
  문장 직접 입력에서만 '~한다.'를 권장 꼴로 본다(원고 전체 점검에서는 보지 않음 — 원고에 '~함' 꼴 줄이 섞여 있어 오탐이 남).
- 후보 수: 기업 기대 시연(「문장정정 후보 5순위 검토자 선택」) — 문장당 최대 5개, 순위를 붙여 검토자가 고른다.
- 역할 경계(요구사항정의서 V0.23 REQ-02-004): 종결·표현처럼 규칙으로 고칠 수 있는 것만 바꾼다. 전문 직무 내용을 새로 만들거나
  교육 내용의 적절성을 판정하지 않는다. AI 후보도 같은 규칙 판정으로 다시 거르고, 원문에 없던 수치·영문·상호가 생기면 버린다.
- 고지: AI가 만든 문장은 집필자 서약서의 고지 대상일 수 있어 후보마다 출처('규칙 기반'·'AI 생성')를 적는다.
"""

from __future__ import annotations

from dataclasses import dataclass

# 문장 종류(id = 화면 이름) → 규정 꼴. 순서가 화면 선택지 순서다.
KINDS = {
    "학습 목표": "~할 수 있다. (주어 없이)",
    "수행 순서": "~한다. (~할 수 있다.도 적합)",
    "교수 방법": "~한다.",
    "학습 방법": "~한다.",
    "안전·유의 사항": "~한다. (권장 꼴)",
    "평가 항목": "~여부 / ~능력 / ~수준 / ~정도 (마침표 없이)",
    "학습명": "~하기",
    "수행 내용 제목": "~하기",
    "학습 내용명": "행동명사로 끝남 (예: ~ 수집, ~ 분석)",
}

SOURCE_RULE = "규칙 기반"
SOURCE_AI = "AI 생성"
NO_SUGGESTION = "추천 없음(사람이 고쳐야 함)"

LLM_TASK = "sentence_suggest"   # ncs_core.llm.ALLOWED_TASKS에 아직 없음 — 추가되기 전에는 AI 후보가 만들어지지 않는다(팀장 요청 이슈)


@dataclass(frozen=True)
class SuggestConfig:
    max_candidates: int = 5        # 문장당 후보 수(순위 1~5)
    max_examples: int = 2          # 같은 원고의 참고 예문 수
    example_min: float = 0.35      # 참고 예문 글자 유사도 하한(difflib ratio)
    high: float = 0.85             # 신뢰도 '높음' 문턱
    medium: float = 0.6            # 신뢰도 '보통' 문턱(아래는 '낮음')
    ai_score: float = 0.55         # AI 후보의 정렬 점수(확신이 높은 규칙 후보보다 아래에 둔다)
    ai_min_similarity: float = 0.6  # AI 후보와 원문의 글자 유사도 하한 — 낮으면 내용을 바꾼 것으로 보고 버린다
    llm_max_sentences: int = 30    # 원고 한 건에서 AI에 물을 문장 수 상한
    llm_context_chars: int = 300   # AI에 함께 보내는 앞뒤 문단 길이

    def confidence(self, score: float) -> str:
        return "높음" if score >= self.high else "보통" if score >= self.medium else "낮음"


DEFAULT_CONFIG = SuggestConfig()
